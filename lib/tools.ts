// Two parallel data sources, on purpose (see README.md, "Ny roa
// rafitra"):
//
// 1. TOOLS — a small, hand-curated list of the tools that already
//    have a real page + component wired up (used by app/page.tsx
//    for the home grid, and by ToolPageClient to pick which
//    component to render).
//
// 2. registryTools / registryCategories — the FULL 63-tool SEO
//    registry extracted from the legacy monolith (CoreRegistry
//    bundle). Not all of these have a page yet — use this as the
//    source when you wire up a new hub (PDF, Network, Calculators…)
//    so the /tools/[slug] route can generate real metadata for it.

// ── Types ────────────────────────────────────────────────────
export interface Tool {
  id: string
  label: string
  frLabel: string
  slug: string          // format: "/bmi-calculator" (ONE leading slash, no "/tools/" prefix)
  cat: 'health' | 'finance' | 'dev' | 'text' | 'convert'
  icon: string
  keywords: string[]
}

export interface RegistryTool {
  id: string
  name: string
  frName: string
  slug: string           // format: "/tools/bmi-calculator" (includes "/tools/" prefix)
  title: string
  frTitle: string
  description: string
  frDescription: string
  keywords: string[]
  frKeywords: string[]
  category: string
  icon: string
  color: string
  tags: string[]
  trending?: boolean
  popular?: boolean
  [key: string]: any // the legacy registry has extra SEO/ads fields we don't type individually
}

export interface RegistryCategory {
  id: string
  slug: string
  [key: string]: any
}

